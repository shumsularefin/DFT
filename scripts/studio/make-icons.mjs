#!/usr/bin/env node
// Builds src/components/studio/icons.generated.ts from a lucide-static package (ISC licence).
// Usage: node scripts/studio/make-icons.mjs <path-to-unpacked-lucide-static/package>
// Only the icons DFT Studio uses are kept, so no icon font or CDN is needed (site CSP is 'self').
import fs from 'node:fs';
import path from 'node:path';

const pkg = process.argv[2];
if (!pkg) {
  console.error('usage: make-icons.mjs <lucide-static package dir>');
  process.exit(2);
}
const NAMES = [
  'book-open',
  'camera',
  'chevron-left',
  'circle-help',
  'clipboard-paste',
  'copy',
  'cpu',
  'download',
  'eraser',
  'file-spreadsheet',
  'folder-open',
  'library',
  'maximize-2',
  'moon',
  'mouse-pointer-2',
  'move',
  'orbit',
  'panel-left',
  'ruler',
  'search',
  'sparkles',
  'spline',
  'sun',
  'trash-2',
  'triangle-right',
  'undo-2',
  'x',
  'zoom-in',
  'redo-2',
  'shield-check',
  'external-link',
  'send',
  'grid-3x3',
  'house',
];
const out = {};
for (const n of NAMES) {
  const svg = fs.readFileSync(path.join(pkg, 'icons', `${n}.svg`), 'utf8');
  const inner = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'));
  out[n] = inner.replace(/\s+/g, ' ').replace(/> </g, '><').trim();
}
const body =
  '// Generated by scripts/studio/make-icons.mjs from lucide-static 0.460.0 (ISC licence). Do not edit.\n' +
  `export const ICONS: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`;
fs.writeFileSync('src/components/studio/icons.generated.ts', body);
console.log(`wrote ${NAMES.length} icons`);
